#!/usr/bin/env bash
# Mark the current top-level Codex session active.
#
# Use this at the start of Codex entry points that do not pass through the
# companion wrapper, such as an API-hosted or in-app Codex session. The Codex
# wrapper also calls this script for top-level invocations.
#
# Responsibilities:
#   1. Write .active-binding.md as PRIMARY=Codex unless AGENT_ROLE=tool.
#   2. Refresh .codex-context.md when a repo-specific exporter exists and the
#      context file is missing or older than 24h.
#   3. Append audit rows to .codex-hook-log.tsv when the logger is installed.

set -euo pipefail

resolve_workspace() {
  if [[ -n "${WORKSPACE:-}" ]]; then
    printf '%s\n' "$WORKSPACE"
  elif git rev-parse --show-toplevel >/dev/null 2>&1; then
    git rev-parse --show-toplevel
  else
    pwd
  fi
}

WORKSPACE="$(resolve_workspace)"
BINDING_FILE="$WORKSPACE/.active-binding.md"
EXPORT_SCRIPT="$WORKSPACE/scripts/export-codex-context.sh"
CTX_FILE="$WORKSPACE/.codex-context.md"
LOG_HELPER="$WORKSPACE/scripts/codex-hook-log.sh"
SOURCE="${1:-codex-session}"

log() {
  [[ -x "$LOG_HELPER" ]] && "$LOG_HELPER" codex-session "$SOURCE" "$@" || true
}

if [[ "${AGENT_ROLE:-}" == "tool" ]]; then
  log skipped-tool "binding preserved"
  exit 0
fi

cat > "$BINDING_FILE" <<EOF
<!-- AUTO-GENERATED by scripts/enter-codex-session.sh ($SOURCE) -->
<!-- DO NOT EDIT. Per-machine state, gitignored. -->
PRIMARY=Codex
REVIEWER=Claude
PUBLISHER=Claude
BOUND_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
BOUND_BY=$SOURCE
EOF

log binding-written "$BINDING_FILE"

if [[ ! -x "$EXPORT_SCRIPT" ]]; then
  log refresh-skipped "export script missing"
  exit 0
fi

if [[ ! -f "$CTX_FILE" ]] || [[ $(find "$CTX_FILE" -mtime +1 -print 2>/dev/null) ]]; then
  "$EXPORT_SCRIPT" >/dev/null
  log refresh-stale-to-fresh "$CTX_FILE"
else
  log refresh-ok "already fresh"
fi
