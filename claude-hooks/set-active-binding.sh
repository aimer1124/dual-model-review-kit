#!/bin/bash
# Claude SessionStart hook: declare PRIMARY=Claude for this session.
#
# Writes .active-binding.md at the repo root so governance text and gate
# scripts know which agent is actually driving the session. Codex sessions
# overwrite the same file via scripts/run-codex-with-context.sh.
#
# Sub-tool invocation contract:
#   When this hook fires inside a sub-tool spawn (typical case: a Codex
#   session that calls `claude -p` for reverse review; the child Claude's
#   SessionStart hooks would otherwise flip the binding), the caller must
#   set AGENT_ROLE=tool before invoking the child. This hook then short-
#   circuits without rewriting the binding file.

set -uo pipefail

# Suppress write when this hook fires inside a sub-tool spawn.
if [[ "${AGENT_ROLE:-}" == "tool" ]]; then
  echo '{"continue":true}'
  exit 0
fi

resolve_workspace() {
  if [[ -n "${WORKSPACE:-}" ]]; then
    printf '%s\n' "$WORKSPACE"
  elif git rev-parse --show-toplevel >/dev/null 2>&1; then
    git rev-parse --show-toplevel
  else
    pwd
  fi
}

WORKSPACE="$(resolve_workspace)"
BINDING_FILE="$WORKSPACE/.active-binding.md"

cat > "$BINDING_FILE" <<EOF
<!-- AUTO-GENERATED by .claude/hooks/set-active-binding.sh -->
<!-- DO NOT EDIT. Per-machine state, gitignored. -->
PRIMARY=Claude
REVIEWER=Codex
PUBLISHER=Claude
BOUND_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
BOUND_BY=claude-session-start-hook
EOF

# Silent success; bubbling additionalContext is left to other SessionStart hooks.
echo '{"continue":true}'
